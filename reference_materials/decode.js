#!/usr/bin/env node
/**
 * De-minify scraped JS and build a chunk/source index.
 * Reads from reference_materials/scraped (and _next/), writes to repo-root scraped-beautified/.
 * Never modifies the original scrape.
 */

import { readFileSync, writeFileSync, mkdirSync, readdirSync, copyFileSync, existsSync } from 'fs';
import { join, dirname, relative } from 'path';
import { fileURLToPath } from 'url';
import beautify from 'js-beautify';

const __dirname = dirname(fileURLToPath(import.meta.url));
const REF_DIR = __dirname;
const REPO_ROOT = join(REF_DIR, '..');
const SCRAPED = join(REF_DIR, 'scraped');
const BEAUTIFIED = join(REPO_ROOT, 'scraped-beautified');

// Patterns to extract for the index (regex source; we'll use global match)
const SENTRY_SOURCE = /data-sentry-source-file["\s]*:["\s]*["']([^"']+\.tsx?)["']/g;
const API_STRINGS = [
  /api\.letta\.com/g,
  /app\.letta\.com/g,
  /web-cdn\.letta\.com/g,
  /localhost:\d+/g,
  /NEXT_PUBLIC_[A-Z_]+/g,
  /\/v1\/[a-zA-Z0-9/_-]*/g,
  /Bearer|Authorization/g,
];

function ensureDir(p) {
  if (!existsSync(p)) mkdirSync(p, { recursive: true });
}

function* walkJs(dir, base = dir) {
  if (!existsSync(dir)) return;
  for (const ent of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, ent.name);
    const rel = relative(base, full);
    if (ent.name === 'node_modules' || ent.name === 'scraped-beautified') continue;
    if (ent.isDirectory()) yield* walkJs(full, base);
    else if (ent.name.endsWith('.js')) yield { full, rel, name: ent.name };
  }
}

function extractHints(code) {
  const sourceFiles = [...new Set([...code.matchAll(SENTRY_SOURCE)].map((m) => m[1]))];
  const notable = new Set();
  for (const re of API_STRINGS) {
    const m = code.match(re);
    if (m) m.forEach((s) => notable.add(s));
  }
  return { sourceFiles, notable: [...notable] };
}

function routeFromRel(rel) {
  const normalized = rel.replace(/\\/g, '/');
  const appMatch = normalized.match(/app\/\([^)]+\)/g);
  if (appMatch) return appMatch.join('/') + '/' + rel.split(/[/\\]/).pop();
  return normalized;
}

function beautifyJs(content) {
  try {
    return beautify.js(content, {
      indent_size: 2,
      max_preserve_newlines: 1,
      preserve_newlines: false,
      space_in_empty_paren: false,
    });
  } catch (err) {
    return content;
  }
}

const index = [];

// 1) scraped/_next and scraped/**/*.js
for (const { full, rel } of walkJs(join(SCRAPED, '_next'), SCRAPED)) {
  const outPath = join(BEAUTIFIED, rel);
  ensureDir(dirname(outPath));
  const content = readFileSync(full, 'utf8');
  const { sourceFiles, notable } = extractHints(content);
  writeFileSync(outPath, beautifyJs(content), 'utf8');
  index.push({
    chunk: rel,
    route: routeFromRel(rel),
    sourceFiles: sourceFiles.slice(0, 20),
    notable: notable.slice(0, 30),
  });
  process.stdout.write('.');
}

// 2) Login-page _next next to this folder (reference_materials/_next)
const rootNext = join(REF_DIR, '_next');
if (existsSync(rootNext)) {
  for (const { full, rel } of walkJs(rootNext, REF_DIR)) {
    const outRel = rel.replace(/^_next\/?/, '_next-root/');
    const outPath = join(BEAUTIFIED, outRel);
    ensureDir(dirname(outPath));
    const content = readFileSync(full, 'utf8');
    const { sourceFiles, notable } = extractHints(content);
    writeFileSync(outPath, beautifyJs(content), 'utf8');
    index.push({
      chunk: outRel,
      route: routeFromRel(outRel),
      sourceFiles: sourceFiles.slice(0, 20),
      notable: notable.slice(0, 30),
    });
    process.stdout.write('.');
  }
}

// 3) Copy CSS so we have a complete mirror (optional; keeps layout same)
function copyDir(src, dest) {
  if (!existsSync(src)) return;
  ensureDir(dest);
  for (const ent of readdirSync(src, { withFileTypes: true })) {
    const s = join(src, ent.name);
    const d = join(dest, ent.name);
    if (ent.isDirectory()) copyDir(s, d);
    else copyFileSync(s, d);
  }
}
copyDir(join(SCRAPED, '_next', 'static', 'css'), join(BEAUTIFIED, '_next', 'static', 'css'));
copyDir(join(SCRAPED, '_next', 'static', 'media'), join(BEAUTIFIED, '_next', 'static', 'media'));

// 4) Write DECODE_INDEX.md
const lines = [
  '# Decode Index',
  '',
  'Chunk → route and source hints. Use this to open the right beautified file and find API/config references.',
  '',
  '| Chunk | Route hint | Source files (Sentry) | Notable strings |',
  '|-------|------------|------------------------|-----------------|',
];

for (const row of index) {
  const chunk = row.chunk.replace(/\|/g, '\\|');
  const route = (row.route || '').slice(0, 50).replace(/\|/g, '\\|');
  const sources = (row.sourceFiles || []).join(', ').replace(/\|/g, '\\|').slice(0, 60);
  const notable = (row.notable || []).join(', ').replace(/\|/g, '\\|').slice(0, 50);
  lines.push(`| ${chunk} | ${route} | ${sources} | ${notable} |`);
}

lines.push('', '---', '', 'Generated by `npm run decode`.');
writeFileSync(join(BEAUTIFIED, 'DECODE_INDEX.md'), lines.join('\n'), 'utf8');
writeFileSync(
  join(BEAUTIFIED, 'decode-index.json'),
  JSON.stringify(index, null, 2),
  'utf8'
);

console.log(`\nDone. Beautified ${index.length} JS chunks → ${BEAUTIFIED}`);
console.log('Index: <repo-root>/scraped-beautified/DECODE_INDEX.md');
